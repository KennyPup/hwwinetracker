// Builds the blank TTB F 5120.17 template for HWWineTracker from Vintrace's filled 2025 PDF (the official fillable form, 01/2018 rev.):
// clears every data field (keeps the form's own label fields), writes src/gen/ttb_template.js (base64).
import fs from 'node:fs';
import { PDFDocument, PDFTextField, PDFCheckBox, PDFDropdown } from 'pdf-lib';
const src = process.argv[2];
const pdf = await PDFDocument.load(fs.readFileSync(src));
const form = pdf.getForm();
const LABELS = /^(Text\d+|t1)$/;
let cleared = 0;
const kinds = {};
for (const f of form.getFields()) {
  const n = f.getName();
  kinds[f.constructor.name] = (kinds[f.constructor.name] || 0) + 1;
  if (LABELS.test(n)) continue;
  if (f instanceof PDFTextField) { if (f.getText()) { f.setText(''); cleared++; } }
  else if (f instanceof PDFCheckBox) { if (f.isChecked()) { f.uncheck(); cleared++; } }
  else if (f instanceof PDFDropdown) { if ((f.getSelected()[0] || ' ') !== ' ') { f.select(' '); cleared++; } }
}
const out = await pdf.save({ useObjectStreams: true });
fs.writeFileSync('tools/ttb/ttb5120_17_blank.pdf', out);
fs.writeFileSync('src/gen/ttb_template.js', '// Blank TTB F 5120.17 (01/2018 rev.) fillable form — generated by tools/ttb/make_template.mjs\nexport const TTB_TEMPLATE = "' + Buffer.from(out).toString('base64') + '";\n');
console.log('fields', form.getFields().length, kinds, 'cleared', cleared, 'bytes', out.length);
